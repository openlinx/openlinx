"""Writes src/openlinx/extract/unicode_scripts.py: the character classes of the word rule and of the
address display (030-add-page-data D8), from one Unicode version's Scripts.txt and
DerivedGeneralCategory.txt, so no column depends on the interpreter's own Unicode version.

The inputs are https://www.unicode.org/Public/<X.Y.Z>/ucd/Scripts.txt and
https://www.unicode.org/Public/<X.Y.Z>/ucd/extracted/DerivedGeneralCategory.txt.

Usage: uv run python scripts/unicode_scripts.py <Scripts-X.Y.Z.txt> \
    <DerivedGeneralCategory-X.Y.Z.txt>
"""

import re
import sys
from collections.abc import Iterable
from pathlib import Path

_OUT = (
    Path(__file__).resolve().parent.parent / "src" / "openlinx" / "extract" / "unicode_scripts.py"
)
_SCRIPTS = frozenset({"Han", "Hiragana", "Katakana"})
# The prolonged sound mark is Common in Scripts.txt; the spec counts it as a kana.
_PROLONGED_SOUND_MARK = 0x30FC
# Shown raw in an address, these hide or spoof what it says.
_KEPT_ENCODED = frozenset({"Cc", "Cf", "Zs", "Zl", "Zp"})
_LINE = re.compile(r"([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)")


def main(scripts_txt: Path, categories_txt: Path) -> None:
    scripts_version = _version(scripts_txt, "Scripts")
    if _version(categories_txt, "DerivedGeneralCategory") != scripts_version:
        sys.exit("Give Scripts.txt and DerivedGeneralCategory.txt of one Unicode version.")
    han_and_kana = {_PROLONGED_SOUND_MARK}
    for first, last, script in _entries(scripts_txt):
        if script in _SCRIPTS:
            han_and_kana.update(range(first, last + 1))
    words: set[int] = set()
    marks: set[int] = set()
    kept: set[int] = set()
    for first, last, category in _entries(categories_txt):
        points = range(first, last + 1)
        if category[0] in "LMN":
            words.update(point for point in points if point not in han_and_kana)
        if category[0] == "M":
            marks.update(points)
        if category in _KEPT_ENCODED:
            kept.update(points)
    _OUT.write_text(
        f'"""Generated by scripts/unicode_scripts.py from Scripts-{scripts_version}.txt and\n'
        f'DerivedGeneralCategory-{scripts_version}.txt."""\n'
        "\n"
        f'UNICODE_VERSION = "{scripts_version}"\n'
        "# Letters, marks and numbers (L, M, N) but Han and kana.\n"
        f"WORD_CHARACTERS = {_table(words)}"
        f"MARKS = {_table(marks)}"
        f"HAN_AND_KANA = {_table(han_and_kana)}"
        "# Controls, format characters, and spaces and separators (Cc, Cf, Zs, Zl, Zp).\n"
        f"KEPT_ENCODED = {_table(kept)}",
        encoding="utf-8",
        newline="\n",
    )


def _version(path: Path, name: str) -> str:
    match = re.match(rf"# {name}-(\d+\.\d+\.\d+)\.txt", path.read_text(encoding="utf-8"))
    if match is None:
        sys.exit(f"{path} is no {name}.txt.")
    return match.group(1)


def _entries(path: Path) -> Iterable[tuple[int, int, str]]:
    for line in path.read_text(encoding="utf-8").splitlines():
        match = _LINE.match(line)
        if match:
            first = int(match.group(1), 16)
            yield first, int(match.group(2) or match.group(1), 16), match.group(3)


def _table(points: set[int]) -> str:
    ranges: list[list[int]] = []
    for point in sorted(points):
        if ranges and ranges[-1][1] == point - 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    rows = "".join(f"    (0x{first:04X}, 0x{last:04X}),\n" for first, last in ranges)
    return f"(\n{rows})\n"


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
