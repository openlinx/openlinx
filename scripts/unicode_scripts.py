"""Writes src/spider/extract/unicode_scripts.py: the characters that the word rule counts one
word each (030-add-page-data D8), from Unicode's Scripts.txt of this Python's version.

Usage: uv run python scripts/unicode_scripts.py <path of Scripts-X.Y.Z.txt>
"""

import re
import sys
import unicodedata
from pathlib import Path

_OUT = Path(__file__).resolve().parent.parent / "src" / "spider" / "extract" / "unicode_scripts.py"
_SCRIPTS = frozenset({"Han", "Hiragana", "Katakana"})
# The prolonged sound mark is Common in Scripts.txt; the spec counts it as a kana.
_PROLONGED_SOUND_MARK = 0x30FC
_LINE = re.compile(r"([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)")


def main(scripts_txt: Path) -> None:
    text = scripts_txt.read_text(encoding="utf-8")
    version = re.match(r"# Scripts-(\d+\.\d+\.\d+)\.txt", text)
    if version is None or version.group(1) != unicodedata.unidata_version:
        sys.exit(f"Give the Scripts.txt of Unicode {unicodedata.unidata_version}, this Python's.")
    points = {_PROLONGED_SOUND_MARK}
    for line in text.splitlines():
        match = _LINE.match(line)
        if match and match.group(3) in _SCRIPTS:
            first = int(match.group(1), 16)
            points.update(range(first, int(match.group(2) or match.group(1), 16) + 1))
    ranges: list[list[int]] = []
    for point in sorted(points):
        if ranges and ranges[-1][1] == point - 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    rows = "".join(f"    (0x{first:04X}, 0x{last:04X}),\n" for first, last in ranges)
    _OUT.write_text(
        f'"""Generated by scripts/unicode_scripts.py from Scripts-{version.group(1)}.txt."""\n'
        "\n"
        f'UNICODE_VERSION = "{version.group(1)}"\n'
        "# Han, Hiragana and Katakana, and U+30FC.\n"
        f"IDEOGRAPHS = (\n{rows})\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main(Path(sys.argv[1]))
