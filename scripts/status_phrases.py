"""Writes src/openlinx/extract/status_phrases.py: the reason phrase of each status code in the IANA
HTTP Status Code Registry (030-add-page-data D19), from scripts/http-status-codes-1.csv.

To refresh: save https://www.iana.org/assignments/http-status-codes/http-status-codes-1.csv over
the snapshot with LF line endings, then give the registry's "Last Updated" date.

Usage: uv run python scripts/status_phrases.py <YYYY-MM-DD>
"""

import csv
import re
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
_SNAPSHOT = _ROOT / "scripts" / "http-status-codes-1.csv"
_OUT = _ROOT / "src" / "openlinx" / "extract" / "status_phrases.py"
# What the registry adds to a phrase, such as "(OBSOLETED)" or a temporary registration's terms.
_ANNOTATION = re.compile(r"\s*\(.*\)$")
_NO_PHRASE = frozenset({"Unassigned", "(Unused)"})


def main(updated: str) -> None:
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", updated) is None:
        sys.exit("Give the registry's Last Updated date as YYYY-MM-DD.")
    with _SNAPSHOT.open(encoding="utf-8", newline="") as snapshot:
        rows = [
            f'    {int(row["Value"])}: "{_ANNOTATION.sub("", row["Description"])}",\n'
            for row in csv.DictReader(snapshot)
            if row["Value"].isdigit() and row["Description"] not in _NO_PHRASE
        ]
    _OUT.write_text(
        '"""Generated by scripts/status_phrases.py from the IANA HTTP Status Code Registry."""\n'
        "\n"
        f'REGISTRY_UPDATED = "{updated}"\n'
        f"STATUS_PHRASES: dict[int, str] = {{\n{''.join(rows)}}}\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main(sys.argv[1])
